"""Tests for the svolmer/quality-playbook compatibility fork (MAF/MCP host).

Covers the four contract-contradiction resolutions recorded in
COMPATIBILITY_FORK.md:

- CC-03: ``finalize-index`` writes the receipted gate verdict into the
  live quality/INDEX.md (last RESULT line wins, never guessed).
- CC-05: Phase 6 completion requires a final INDEX gate_verdict
  (covered in test_run_state_lib).
- CC-15: AGENTS.md is generated by a bundled module, written before the
  Phase 6 gate and regenerated after the verdict; a QPB-managed
  AGENTS.md is not a source-edit violation, an operator-authored one is.
- CC-16: iteration handoff is prose-only (SKILL.md / phase6.md /
  AGENTS.md); pinned here by a text check.
"""

from __future__ import annotations

import io
import json
import re
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from datetime import datetime, timezone
from pathlib import Path
from unittest import mock

from bin import archive_lib, quality_playbook, run_playbook


REPO_ROOT = Path(__file__).resolve().parents[2]
SKILL_ROOT = REPO_ROOT / "plugins" / "quality-playbook" / "skills" / "quality-playbook"

_INDEX_TEMPLATE = (
    "# Run index\n\n"
    "Prose before the block.\n\n"
    "```json\n{payload}\n```\n\n"
    "Prose after the block.\n"
)


def _make_run(tmp: Path, gate_log: str, *, payload: dict | None = None) -> Path:
    repo = tmp / "repo"
    results = repo / "quality" / "results"
    results.mkdir(parents=True)
    (results / "quality-gate.log").write_text(gate_log, encoding="utf-8")
    if payload is None:
        payload = {
            "run_timestamp_start": "2026-10-14T10:00:00Z",
            "run_timestamp_end": None,
            "duration_seconds": None,
            "summary": {"gate_verdict": "pending", "bugs": 3},
        }
    (repo / "quality" / "INDEX.md").write_text(
        _INDEX_TEMPLATE.format(payload=json.dumps(payload, indent=2)),
        encoding="utf-8",
    )
    return repo


def _index_payload(repo: Path) -> dict:
    text = (repo / "quality" / "INDEX.md").read_text(encoding="utf-8")
    match = re.search(r"```json\n(.*?)\n```", text, re.DOTALL)
    assert match is not None
    return json.loads(match.group(1))


_NOW = datetime(2026, 10, 14, 10, 5, 30, tzinfo=timezone.utc)


class FinalizeIndexTests(unittest.TestCase):
    """CC-03: receipted gate verdict → INDEX summary.gate_verdict."""

    def test_maps_each_gate_result_token(self):
        cases = {
            "RESULT: GATE PASSED\n": "pass",
            "RESULT: GATE PASSED WITH CLEANUP NEEDED — 2 audit record-keeping gap(s)\n":
                "pass-with-cleanup",
            "RESULT: GATE FAILED — 4 substantive issue(s) must be fixed\n": "fail",
        }
        for log, expected in cases.items():
            with self.subTest(expected=expected), tempfile.TemporaryDirectory() as d:
                repo = _make_run(Path(d), "Total: 0 FAIL, 1 WARN\n" + log)
                result = archive_lib.finalize_index_gate_verdict(repo, now=_NOW)
                self.assertEqual(result["gate_verdict"], expected)
                payload = _index_payload(repo)
                self.assertEqual(payload["summary"]["gate_verdict"], expected)
                self.assertEqual(payload["summary"]["bugs"], 3)
                self.assertEqual(payload["run_timestamp_end"], "2026-10-14T10:05:30Z")
                self.assertEqual(payload["duration_seconds"], 330)

    def test_last_result_line_wins(self):
        log = (
            "RESULT: GATE FAILED — 1 substantive issue(s) must be fixed\n"
            "... fixed, re-ran ...\n"
            "RESULT: GATE PASSED\n"
        )
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), log)
            result = archive_lib.finalize_index_gate_verdict(repo, now=_NOW)
            self.assertEqual(result["result"], "PASSED")
            self.assertEqual(_index_payload(repo)["summary"]["gate_verdict"], "pass")

    def test_no_result_line_raises_and_writes_nothing(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "Total: 2 FAIL, 0 WARN\n")
            before = (repo / "quality" / "INDEX.md").read_bytes()
            with self.assertRaises(archive_lib.ArchiveError):
                archive_lib.finalize_index_gate_verdict(repo, now=_NOW)
            self.assertEqual((repo / "quality" / "INDEX.md").read_bytes(), before)

    def test_missing_gate_log_raises(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "")
            (repo / "quality" / "results" / "quality-gate.log").unlink()
            with self.assertRaises(archive_lib.ArchiveError):
                archive_lib.finalize_index_gate_verdict(repo, now=_NOW)

    def test_index_without_json_block_raises(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "RESULT: GATE PASSED\n")
            (repo / "quality" / "INDEX.md").write_text("# Index\n", encoding="utf-8")
            with self.assertRaises(archive_lib.ArchiveError):
                archive_lib.finalize_index_gate_verdict(repo, now=_NOW)

    def test_text_outside_json_block_is_preserved(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "RESULT: GATE PASSED\n")
            archive_lib.finalize_index_gate_verdict(repo, now=_NOW)
            text = (repo / "quality" / "INDEX.md").read_text(encoding="utf-8")
            self.assertTrue(text.startswith("# Run index\n\nProse before the block.\n\n```json\n"))
            self.assertTrue(text.endswith("\n```\n\nProse after the block.\n"))

    def test_finalized_index_satisfies_phase6_completion(self):
        from bin import run_state_lib

        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "Total: 0 FAIL\nRESULT: GATE PASSED\n")
            (repo / "quality" / "PROGRESS.md").write_text(
                "# Progress\n\n## Terminal Gate Verification\n\nPASSED\n",
                encoding="utf-8",
            )
            ok, reason = run_state_lib.validate_phase_artifacts(repo / "quality", 6)
            self.assertFalse(ok)
            self.assertIn("not final", reason)
            archive_lib.finalize_index_gate_verdict(repo, now=_NOW)
            ok, reason = run_state_lib.validate_phase_artifacts(repo / "quality", 6)
            self.assertTrue(ok, msg=reason)


class CliTests(unittest.TestCase):
    """The new `quality_playbook` subcommands used by the Mode A prompts."""

    def _run(self, argv):
        out, err = io.StringIO(), io.StringIO()
        with redirect_stdout(out), redirect_stderr(err):
            code = quality_playbook.main(argv)
        return code, out.getvalue(), err.getvalue()

    def test_finalize_index_cli_prints_receipt(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "RESULT: GATE PASSED WITH CLEANUP NEEDED — 1 audit record-keeping gap(s)\n")
            code, out, _ = self._run(["finalize-index", str(repo)])
            self.assertEqual(code, 0)
            self.assertIn("gate_result: RESULT: GATE PASSED WITH CLEANUP NEEDED", out)
            self.assertIn("gate_verdict: pass-with-cleanup", out)
            self.assertIn("duration_seconds:", out)

    def test_finalize_index_cli_fails_without_gate_result(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "nothing here\n")
            code, _, err = self._run(["finalize-index", str(repo)])
            self.assertEqual(code, 1)
            self.assertIn("ERROR:", err)

    def test_agents_md_cli_writes_then_regenerates_then_preserves(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "RESULT: GATE PASSED\n")
            code, out, _ = self._run(["agents-md", str(repo)])
            self.assertEqual(code, 0)
            self.assertIn("AGENTS.md wrote", out)
            agents = repo / "AGENTS.md"
            self.assertTrue(archive_lib.is_qpb_managed_agents_md(agents))

            code, out, _ = self._run(["agents-md", str(repo)])
            self.assertEqual(code, 0)
            self.assertIn("AGENTS.md regenerated", out)

            agents.write_text("# Operator guide\n", encoding="utf-8")
            code, out, _ = self._run(["agents-md", str(repo)])
            self.assertEqual(code, 0)
            self.assertIn("AGENTS.md preserved", out)
            self.assertEqual(agents.read_text(encoding="utf-8"), "# Operator guide\n")

    def test_subcommands_listed_in_usage(self):
        code, out, err = self._run(["--help"])
        self.assertIn("finalize-index", out + err)
        self.assertIn("agents-md", out + err)


class AgentsMdTests(unittest.TestCase):
    """CC-15: bundled generator, sentinel detection, run_playbook aliases."""

    def test_is_qpb_managed(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / "AGENTS.md"
            self.assertFalse(archive_lib.is_qpb_managed_agents_md(path))
            path.write_text("# Operator\n", encoding="utf-8")
            self.assertFalse(archive_lib.is_qpb_managed_agents_md(path))
            path.write_text(archive_lib.QPB_AGENTS_SENTINEL + "\n# x\n", encoding="utf-8")
            self.assertTrue(archive_lib.is_qpb_managed_agents_md(path))
            # Prefix match: other QPB versions are still QPB-managed.
            path.write_text("<!-- generated by QPB v9.9.9 -->\n", encoding="utf-8")
            self.assertTrue(archive_lib.is_qpb_managed_agents_md(path))

    def test_run_playbook_aliases_point_at_bundled_generator(self):
        self.assertIs(run_playbook._generate_agents_md_content,
                      archive_lib.generate_agents_md_content)
        self.assertIs(run_playbook._safe_write_agents_md,
                      archive_lib.safe_write_agents_md)
        self.assertEqual(run_playbook.QPB_AGENTS_SENTINEL, archive_lib.QPB_AGENTS_SENTINEL)

    def test_generated_content_starts_with_sentinel(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "RESULT: GATE PASSED\n")
            content = archive_lib.generate_agents_md_content(repo)
            self.assertTrue(content.startswith(archive_lib.QPB_AGENTS_SENTINEL_PREFIX))


class _Args:
    """Minimal args namespace for _log_phase_completion."""

    def __getattr__(self, name):
        return None


class ModeBPhase6OrderingTests(unittest.TestCase):
    """CC-15: AGENTS.md exists before the gate runs and is regenerated
    after the verdict, regardless of the verdict."""

    def _drive(self, phase, finalizer_status, gate_log):
        calls = []
        with tempfile.TemporaryDirectory() as d:
            repo = Path(d) / "repo"
            (repo / "quality" / "results").mkdir(parents=True)
            (repo / "quality" / "results" / "quality-gate.log").write_text(
                gate_log, encoding="utf-8")

            def _agents(_repo, _log, *, when):
                calls.append(f"agents:{when}")

            def _finalize(*_a, **_k):
                calls.append("finalize")
                return finalizer_status

            def _index(*_a, **_k):
                calls.append("index")

            with mock.patch.object(run_playbook, "_write_agents_md", side_effect=_agents), \
                 mock.patch.object(run_playbook, "_finalize_iteration", side_effect=_finalize), \
                 mock.patch.object(run_playbook, "write_live_index_final", side_effect=_index), \
                 mock.patch.object(run_playbook, "archive_lib"):
                run_playbook._log_phase_completion(
                    repo, phase, repo / "run.log", _Args(), "20261014-100000",
                )
        return calls

    def test_phase6_order_on_pass(self):
        calls = self._drive("6", "pass", "RESULT: GATE PASSED\n")
        self.assertEqual(
            calls, ["agents:pre-gate", "finalize", "index", "agents:post-verdict"])

    def test_phase6_regenerates_even_on_fail(self):
        calls = self._drive(
            "6", "fail", "RESULT: GATE FAILED — 1 substantive issue(s) must be fixed\n")
        self.assertEqual(calls[0], "agents:pre-gate")
        self.assertEqual(calls[-1], "agents:post-verdict")
        self.assertLess(calls.index("agents:pre-gate"), calls.index("finalize"))

    def test_phase5_close_writes_agents_md(self):
        calls = self._drive("5", "pass", "")
        self.assertEqual(calls, ["agents:pre-gate"])


class _FakeCompleted:
    def __init__(self, returncode, stdout="", stderr=""):
        self.returncode = returncode
        self.stdout = stdout
        self.stderr = stderr


class FinalizerAgentsMdExemptionTests(unittest.TestCase):
    """CC-15: the source-edit guardrail excuses a QPB-managed AGENTS.md
    only; an edited operator-authored AGENTS.md still aborts the run."""

    def _finalize(self, agents_text):
        with tempfile.TemporaryDirectory() as d:
            repo = Path(d) / "repo"
            (repo / "quality").mkdir(parents=True)
            gate = repo / ".github" / "skills"
            gate.mkdir(parents=True)
            (gate / "quality_gate.py").write_text("# stub\n", encoding="utf-8")
            (repo / "AGENTS.md").write_text(agents_text, encoding="utf-8")
            with mock.patch("bin.run_state_lib.validate_no_source_edits",
                            return_value=(False, ["AGENTS.md"])), \
                 mock.patch("bin.run_playbook.subprocess.run",
                            return_value=_FakeCompleted(0, stdout="RESULT: GATE PASSED\n")):
                return run_playbook._finalize_iteration(repo, "post-test", repo / "run.log")

    def test_qpb_managed_agents_md_is_excused(self):
        status = self._finalize(archive_lib.QPB_AGENTS_SENTINEL + "\n# Generated\n")
        self.assertEqual(status, "pass")

    def test_operator_agents_md_edit_is_still_a_violation(self):
        status = self._finalize("# Operator guide\n")
        self.assertEqual(status, "aborted")


class ProseContractTests(unittest.TestCase):
    """Pin the prose halves of CC-03 / CC-15 / CC-16."""

    def _read(self, rel):
        return (SKILL_ROOT / rel).read_text(encoding="utf-8")

    def test_phase6_prompt_has_parent_finalization_and_iteration_handoff(self):
        text = self._read("phase_prompts/phase6.md")
        self.assertIn("finalize-index", text)
        self.assertIn("agents-md", text)
        self.assertIn("--next-iteration --strategy", text)
        self.assertNotIn("--full-run", text.replace("never `--full-run`", ""))

    def test_auditor_checks_index_verdict_mapping(self):
        text = self._read("phase_prompts/phase6_auditor.md")
        self.assertIn("pass-with-cleanup", text)
        self.assertIn("finalize-index", text)

    def test_phase5_index_enum_includes_pass_with_cleanup(self):
        text = self._read("phase_prompts/phase5.md")
        self.assertIn("pass-with-cleanup", text)
        self.assertIn("agents-md", text)

    def test_skill_md_iteration_rule(self):
        text = (REPO_ROOT / "SKILL.md").read_text(encoding="utf-8")
        for strategy in ("gap", "unfiltered", "parity", "adversarial"):
            self.assertIn(f"--next-iteration --strategy {strategy}", text)


