_INDEX_TEMPLATE = (
    "# Run index\n\n"
    "Prose before the block.\n\n"
    "```json\n{payload}\n```\n\n"
    "Prose after the block.\n"
)


def _make_run(tmp: Path, gate_log: str, *, payload: dict | None = None) -> Path:
    repo = tmp / "repo"
    results = repo / "quality" / "results"
    results.mkdir(parents=True)
    (results / "quality-gate.log").write_text(gate_log, encoding="utf-8")
    if payload is None:
        payload = {
            "run_timestamp_start": "2026-10-14T10:00:00Z",
            "run_timestamp_end": None,
            "duration_seconds": None,
            "summary": {"gate_verdict": "pending", "bugs": 3},
        }
    (repo / "quality" / "INDEX.md").write_text(
        _INDEX_TEMPLATE.format(payload=json.dumps(payload, indent=2)),
        encoding="utf-8",
    )
    return repo


def _index_payload(repo: Path) -> dict:
    text = (repo / "quality" / "INDEX.md").read_text(encoding="utf-8")
    match = re.search(r"```json\n(.*?)\n```", text, re.DOTALL)
    assert match is not None
    return json.loads(match.group(1))


_NOW = datetime(2026, 10, 14, 10, 5, 30, tzinfo=timezone.utc)


class FinalizeIndexTests(unittest.TestCase):
    """CC-03: receipted gate verdict → INDEX summary.gate_verdict."""

    def test_maps_each_gate_result_token(self):
        cases = {
            "RESULT: GATE PASSED\n": "pass",
            "RESULT: GATE PASSED WITH CLEANUP NEEDED — 2 audit record-keeping gap(s)\n":
                "pass-with-cleanup",
            "RESULT: GATE FAILED — 4 substantive issue(s) must be fixed\n": "fail",
        }
        for log, expected in cases.items():
            with self.subTest(expected=expected), tempfile.TemporaryDirectory() as d:
                repo = _make_run(Path(d), "Total: 0 FAIL, 1 WARN\n" + log)
                result = archive_lib.finalize_index_gate_verdict(repo, now=_NOW)
                self.assertEqual(result["gate_verdict"], expected)
                payload = _index_payload(repo)
                self.assertEqual(payload["summary"]["gate_verdict"], expected)
                self.assertEqual(payload["summary"]["bugs"], 3)
                self.assertEqual(payload["run_timestamp_end"], "2026-10-14T10:05:30Z")
                self.assertEqual(payload["duration_seconds"], 330)

    def test_last_result_line_wins(self):
        log = (
            "RESULT: GATE FAILED — 1 substantive issue(s) must be fixed\n"
            "... fixed, re-ran ...\n"
            "RESULT: GATE PASSED\n"
        )
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), log)
            result = archive_lib.finalize_index_gate_verdict(repo, now=_NOW)
            self.assertEqual(result["result"], "PASSED")
            self.assertEqual(_index_payload(repo)["summary"]["gate_verdict"], "pass")

    def test_no_result_line_raises_and_writes_nothing(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "Total: 2 FAIL, 0 WARN\n")
            before = (repo / "quality" / "INDEX.md").read_bytes()
            with self.assertRaises(archive_lib.ArchiveError):
                archive_lib.finalize_index_gate_verdict(repo, now=_NOW)
            self.assertEqual((repo / "quality" / "INDEX.md").read_bytes(), before)

    def test_missing_gate_log_raises(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "")
            (repo / "quality" / "results" / "quality-gate.log").unlink()
            with self.assertRaises(archive_lib.ArchiveError):
                archive_lib.finalize_index_gate_verdict(repo, now=_NOW)

    def test_index_without_json_block_raises(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "RESULT: GATE PASSED\n")
            (repo / "quality" / "INDEX.md").write_text("# Index\n", encoding="utf-8")
            with self.assertRaises(archive_lib.ArchiveError):
                archive_lib.finalize_index_gate_verdict(repo, now=_NOW)

    def test_text_outside_json_block_is_preserved(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "RESULT: GATE PASSED\n")
            archive_lib.finalize_index_gate_verdict(repo, now=_NOW)
            text = (repo / "quality" / "INDEX.md").read_text(encoding="utf-8")
            self.assertTrue(text.startswith("# Run index\n\nProse before the block.\n\n```json\n"))
            self.assertTrue(text.endswith("\n```\n\nProse after the block.\n"))

    def test_finalized_index_satisfies_phase6_completion(self):
        from bin import run_state_lib

        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "Total: 0 FAIL\nRESULT: GATE PASSED\n")
            (repo / "quality" / "PROGRESS.md").write_text(
                "# Progress\n\n## Terminal Gate Verification\n\nPASSED\n",
                encoding="utf-8",
            )
            ok, reason = run_state_lib.validate_phase_artifacts(repo / "quality", 6)
            self.assertFalse(ok)
            self.assertIn("not final", reason)
            archive_lib.finalize_index_gate_verdict(repo, now=_NOW)
            ok, reason = run_state_lib.validate_phase_artifacts(repo / "quality", 6)
            self.assertTrue(ok, msg=reason)


class CliTests(unittest.TestCase):
    """The new `quality_playbook` subcommands used by the Mode A prompts."""

    def _run(self, argv):
        out, err = io.StringIO(), io.StringIO()
        with redirect_stdout(out), redirect_stderr(err):
            code = quality_playbook.main(argv)
        return code, out.getvalue(), err.getvalue()

    def test_finalize_index_cli_prints_receipt(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "RESULT: GATE PASSED WITH CLEANUP NEEDED — 1 audit record-keeping gap(s)\n")
            code, out, _ = self._run(["finalize-index", str(repo)])
            self.assertEqual(code, 0)
            self.assertIn("gate_result: RESULT: GATE PASSED WITH CLEANUP NEEDED", out)
            self.assertIn("gate_verdict: pass-with-cleanup", out)
            self.assertIn("duration_seconds:", out)

    def test_finalize_index_cli_fails_without_gate_result(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "nothing here\n")
            code, _, err = self._run(["finalize-index", str(repo)])
            self.assertEqual(code, 1)
            self.assertIn("ERROR:", err)

    def test_agents_md_cli_writes_then_regenerates_then_preserves(self):
        with tempfile.TemporaryDirectory() as d:
            repo = _make_run(Path(d), "RESULT: GATE PASSED\n")
            code, out, _ = self._run(["agents-md", str(repo)])
            self.assertEqual(code, 0)
            self.assertIn("AGENTS.md wrote", out)
            agents = repo / "AGENTS.md"
            self.assertTrue(archive_lib.is_qpb_managed_agents_md(agents))

            code, out, _ = self._run(["agents-md", str(repo)])
            self.assertEqual(code, 0)
            self.assertIn("AGENTS.md regenerated", out)

            agents.write_text("# Operator guide\n", encoding="utf-8")
            code, out, _ = self._run(["agents-md", str(repo)])
            self.assertEqual(code, 0)
            self.assertIn("AGENTS.md preserved", out)
            self.assertEqual(agents.read_text(encoding="utf-8"), "# Operator guide\n")

    def test_subcommands_listed_in_usage(self):
        code, out, err = self._run(["--help"])
        self.assertIn("finalize-index", out + err)
        self.assertIn("agents-md", out + err)


